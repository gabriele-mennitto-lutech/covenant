import * as dotenv from 'dotenv';
dotenv.config();
import path from 'node:path';

import express from 'express';
import cors from 'cors';
import bodyParser from 'body-parser';
import swaggerUi from 'swagger-ui-express';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import { logger } from './utils/syslogger';
import { loadInitialData } from './data/hostsStore';
import { backendOpenApiSpec } from './swagger';
import { authMiddleware } from './middleware/auth';

import hostsRouter from './routes/hosts';
import sitesRouter from './routes/sites';
import externalRouter from './routes/external';
import settingsRouter from './routes/settings';
import authRouter from './routes/auth';
import servicesRouter from './routes/services';
import logsRouter from './routes/logs';
import mailingRouter from './routes/mailing';
import notificationsRouter from './routes/notifications';
import cvesRouter from './routes/cves';
import crossSourceRouter from './routes/crossSource';

const app = express();
// Deployment con un solo reverse proxy IIS: legge X-Forwarded-For.
app.set('trust proxy', 1);
const PORT = process.env.PORT || 9991;

app.use(helmet());
app.use(cors({
    origin: process.env.FRONTEND_URL || 'http://localhost:4200',
    credentials: true
}));
app.use(bodyParser.json());

const apiLimiter = rateLimit({
    windowMs: 15 * 60 * 1000, // 15 minutes
    max: 1500,
    message: { error: 'Too many requests, please try again later.' }
});
app.use('/api', apiLimiter);

// Initialize memory store by fetching from dataservice
loadInitialData();

// Protect all API routes.
// /api/auth/login is explicitly exempted in authMiddleware.
app.use('/api', authMiddleware);

// Register Routers
app.use('/api/auth', authRouter);
app.use('/api/hosts', hostsRouter);
app.use('/api/sites', sitesRouter);
app.use('/api/services', servicesRouter);
app.use('/api/external', externalRouter);
app.use('/api/settings', settingsRouter);
app.use('/api/logs', logsRouter);
app.use('/api/mailing', mailingRouter);
app.use('/api/notifications', notificationsRouter);
app.use('/api/cves', cvesRouter);
app.use('/api/cross-source', crossSourceRouter);
app.get('/api-docs.json', (req, res) => {
    res.json(backendOpenApiSpec);
});
app.use('/api-docs', swaggerUi.serve, swaggerUi.setup(backendOpenApiSpec));

// Serve Frontend Documentation generated by Compodoc
app.use('/fe-docs', express.static(path.join(__dirname, '../public/frontend-docs')));

// Fallback logic
app.get('/', (req, res) => {
    res.send('Covenant SOC INFRA Backend API is running.');
});

// Global Error Handler
app.use((err: any, req: express.Request, res: express.Response, next: express.NextFunction) => {
    logger.error('Unhandled Server Error:', err);
    res.status(500).json({ error: 'Internal Server Error' });
});

app.listen(PORT, () => {
    logger.info(`Backend service is running on port ${PORT}`);
});
